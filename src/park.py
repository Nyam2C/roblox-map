def strips(poly_px, geo, frame, step=8.0):
    """A polygon (photo pixels) as horizontal strips {x0, x1, z} every `step` studs (shapely does the clipping)."""
    from shapely.geometry import LineString, Polygon
    pts = [layout.to_studs(frame, *geo.to_latlon(x, y)) for x, y in poly_px]
    poly = Polygon(pts).buffer(0).intersection(cell_poly(frame))
    out = []
    if poly.is_empty:
        return out
    x0, z0, x1, z1 = poly.bounds
    z = z0 + step / 2
    while z < z1:
        cut = poly.intersection(LineString([(x0 - 1, z), (x1 + 1, z)]))
        for seg in getattr(cut, "geoms", [cut]):
            if seg.length > 1.0:
                xs = [c[0] for c in seg.coords]
                out.append([round(min(xs), 2), round(max(xs), 2), round(z, 2)])
        z += step
    return out


def cell_poly(frame):
    """The cell's hexagon in studs, 2 studs in: nothing of the park hangs past the built ground."""
    import h3
    from shapely.geometry import Polygon
    return Polygon([layout.to_studs(frame, *p) for p in h3.cell_to_boundary(CELL)]).buffer(-2.0)


def build() -> dict:
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    meta = json.loads(Path(spec["photo"]).with_suffix(".json").read_text())
    geo = Georef(int(meta["tile_x0"]), int(meta["tile_y0"]))
    frame = layout.Frame.from_cfg(common.cell_config(common.load_config(), CELL))
    s = frame.studs_per_m
    P = lambda xy: [round(v, 2) for v in layout.to_studs(frame, *geo.to_latlon(*xy))]  # noqa: E731
    rgb = lambda v, d: [int(c) for c in (v or d)]  # noqa: E731
    from shapely.geometry import LineString, Point
    hexagon = cell_poly(frame)
    paths = []
    for a in spec.get("paths") or []:
        if len(a.get("pts_px") or []) < 2:
            continue
        cut = LineString([P(p) for p in a["pts_px"]]).intersection(hexagon.buffer(-float(a.get("width_m", 4)) * s / 2))
        for seg in getattr(cut, "geoms", [cut]):
            if seg.geom_type == "LineString" and seg.length > 2:
                paths.append({"pts": [[round(x, 2), round(z, 2)] for x, z in seg.coords], "w": round(float(a.get("width_m", 4)) * s, 2),
                              "rgb": rgb(a.get("rgb"), (190, 172, 150))})
    inside = lambda a, r: hexagon.contains(Point(*P(a["c_px"])).buffer(r))  # noqa: E731
    out = {"paths": paths,
           "plazas": [{**dict(zip(("x", "z"), P(a["c_px"]))), "r": round(float(a.get("r_m", 10)) * s, 2), "rgb": rgb(a.get("rgb"), (196, 176, 156)),
                       "kind": a.get("kind", "round")} for a in spec.get("plazas") or [] if inside(a, float(a.get("r_m", 10)) * s)],
           "lawns": [{"step": 8.0, "strips": strips(a["poly_px"], geo, frame)} for a in spec.get("lawns") or [] if len(a.get("poly_px") or []) >= 3],
           "water": [{"step": 8.0, "strips": strips(a["poly_px"], geo, frame)} for a in spec.get("water") or [] if len(a.get("poly_px") or []) >= 3],
           "domes": [{**dict(zip(("x", "z"), P(a["c_px"]))), "r": round(float(a.get("r_m", 6)) * s, 2), "rgb": rgb(a.get("rgb"), (200, 220, 225))}
                     for a in spec.get("domes") or [] if inside(a, float(a.get("r_m", 6)) * s)]}
    t = spec.get("tower") or {}
    out["tower"] = {**dict(zip(("x", "z"), P(t["c_px"]))), "h": round(float(t.get("height_m") or 20) * s, 2), "rgb": rgb(t.get("rgb"), (220, 222, 225))} if t.get("c_px") else None
    g = spec.get("stage") or {}
    out["stage"] = {**dict(zip(("x", "z"), P(g["c_px"]))), "w": round(float(g.get("w_m") or 16) * s, 2), "d": round(float(g.get("d_m") or 10) * s, 2),
                    "yaw": float(g.get("yaw_deg") or 0)} if g.get("c_px") else None
    return out


def lua(v) -> str:
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(round(float(v), 3))
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    return "{" + ", ".join(f"{k} = {lua(x)}" for k, x in v.items()) + "}"


if __name__ == "__main__":
    data = build()
    OUT.write_text(LUAU.replace("--[[DATA]]", lua(data)), encoding="utf-8")
    clear = []  # no satellite tree on the plazas, water, domes, tower and stage
    for kind in ("plazas", "domes"):
        for a in data[kind]:
            clear.append({"name": kind, "x": a["x"], "z": a["z"], "yaw": 0.0, "w": 2 * a["r"] + 4, "d": 2 * a["r"] + 4})
    for kind in ("tower", "stage"):
        a = data[kind]
        if a:
            r = a.get("w", 20.0)
            clear.append({"name": kind, "x": a["x"], "z": a["z"], "yaw": 0.0, "w": r + 8, "d": r + 8})
    for w in data["water"]:
        for x0, x1, z in w["strips"]:
            clear.append({"name": "water", "x": (x0 + x1) / 2, "z": z, "yaw": 0.0, "w": x1 - x0, "d": 8.0})
    path = common.cell_file(common.load_config(), CELL, "courts")
    old = json.loads(path.read_text(encoding="utf-8"))["clear"] if path.exists() else []
    keep = [c for c in old if c["name"] not in ("plazas", "domes", "tower", "stage", "water")]
    path.write_text(json.dumps({"cell_id": CELL, "note": "hand-made rectangles (studs); no satellite tree inside", "clear": keep + clear},
                               ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(OUT, {k: len(v) if isinstance(v, list) else bool(v) for k, v in data.items()})
