"""미리내공원 courts (cell 8930e0af147ffff) -> studio/manual/bucheon-dodang/Courts.luau.

Neither OSM nor V-World has them (user list 2026-10-15, approved with "다 처리"). Traced on the V-World z19 photo of the cell
(data/satellite/8930e0af147ffff-z19.jpg pixels, 0.237 m a pixel): three clay tennis blocks (orange, found by colour: a double
block of 33 x 32 m and two singles of about 33 x 16 m) and a green futsal pitch of 25 x 17 m in a dark fence, read off a 3x crop.
Tennis: doubles court lines (23.77 x 10.97 m, singles 8.23 m, service lines 6.40 m from the net), a net on posts, a green chain
fence. Futsal: turf, boundary, half line, centre circle, goals, fence. Each court is its own Model so settleManual lifts it.

Usage (repo root): uv run src/courts.py   (then anchors.py script --name Courts and execute_luau, as for the other Manual scripts)
"""
from __future__ import annotations

import json
import math
from pathlib import Path

from shapely.geometry import MultiPoint

import common
import layout
from trees import Georef

OUT = Path("studio/manual/bucheon-dodang/Courts.luau")
CELL = "8930e0af147ffff"
# (name, kind, satellite pixel points of the block)
COURTS = (
    ("TennisWest", "tennis", [(850, 1131), (712, 1112), (694, 1248), (832, 1266)]),
    ("TennisEast", "tennis", [(1409, 1346), (1434, 1212), (1368, 1199), (1344, 1333)]),
    ("TennisSouth", "tennis", [(1310, 1495), (1376, 1505), (1386, 1434), (1320, 1424), (1351, 1572), (1360, 1503), (1307, 1496), (1298, 1566)]),
    ("Futsal", "futsal", [(1220, 1177), (1292, 1182), (1280, 1288), (1207, 1282)]),
)
SUB_COURT_M = 16.0  # a tennis block holds round(width / 16 m) courts side by side


def blocks() -> list[dict]:
    """Each court block as centre (studs), yaw (degrees, the long side along the part's Z), length and width (studs)."""
    meta = json.loads(Path(f"data/satellite/{CELL}-z19.json").read_text())
    geo = Georef(int(meta["tile_x0"]), int(meta["tile_y0"]))
    frame = layout.Frame.from_cfg(common.cell_config(common.load_config(), CELL))
    out = []
    for name, kind, px in COURTS:
        rect = MultiPoint(px).minimum_rotated_rectangle
        cs = [layout.to_studs(frame, *geo.to_latlon(x, y)) for x, y in list(rect.exterior.coords)[:4]]
        cx, cz = sum(c[0] for c in cs) / 4, sum(c[1] for c in cs) / 4
        e1, e2 = (cs[1][0] - cs[0][0], cs[1][1] - cs[0][1]), (cs[2][0] - cs[1][0], cs[2][1] - cs[1][1])
        long_, short = (e1, e2) if math.hypot(*e1) >= math.hypot(*e2) else (e2, e1)
        yaw = math.degrees(math.atan2(long_[0], long_[1]))  # the part's Z axis along the long side
        out.append({"name": name, "kind": kind, "x": round(cx, 2), "z": round(cz, 2), "yaw": round(yaw, 2),
                    "length": round(math.hypot(*long_), 2), "width": round(math.hypot(*short), 2),
                    "n": max(1, round(math.hypot(*short) / frame.studs_per_m / SUB_COURT_M)) if kind == "tennis" else 1})
    return out


LUAU = r'''-- Manual courts of 미리내공원 (cell 8930e0af147ffff), v1 (2026-10-15). Generated by src/courts.py from the satellite photo;
-- change courts.py, not the table. Creates only; made only when Manual/Courts does not exist (to redo it delete Manual/Courts).
local manual = workspace:FindFirstChild("Manual")
if not manual then manual = Instance.new("Folder") manual.Name = "Manual" manual.Parent = workspace end
if manual:FindFirstChild("Courts") then return "Manual/Courts is already there: left alone" end
local root = Instance.new("Folder") root.Name = "Courts"
local COURTS = --[[DATA]]
local S = 3.6 -- studs a metre
local TOP = 0.42 -- surface top: over the sidewalks
local count = 0
local function part(parent, name, size, cf, material, rgb, opts)
	local p = Instance.new("Part")
	p.Name = name p.Anchored = true p.Size = size p.CFrame = cf
	p.Material = material p.Color = Color3.fromRGB(rgb[1], rgb[2], rgb[3])
	p.TopSurface = Enum.SurfaceType.Smooth p.BottomSurface = Enum.SurfaceType.Smooth
	if opts then for k, v in opts do p[k] = v end end
	p.Parent = parent
	count += 1
	return p
end
local WHITE, CLAY, TURF, FENCE, NET = {236, 236, 230}, {184, 104, 66}, {46, 112, 70}, {40, 84, 58}, {30, 32, 34}
local LINE = 0.1 * S
local function fence(m, at, L, W, h)
	for i, s in ipairs({ { 0, L / 2, W, 0 }, { 0, -L / 2, W, 0 }, { W / 2, 0, L, 90 }, { -W / 2, 0, L, 90 } }) do
		local cf = at * CFrame.new(s[1], h / 2, s[2]) * CFrame.Angles(0, math.rad(s[4]), 0)
		part(m, "Fence" .. i, Vector3.new(s[3], h, 0.15), cf, Enum.Material.DiamondPlate, FENCE, { Transparency = 0.55, CanCollide = true })
		part(m, "Rail" .. i, Vector3.new(s[3], 0.3, 0.3), cf * CFrame.new(0, h / 2, 0), Enum.Material.Metal, FENCE)
	end
	for _, c in ipairs({ { 1, 1 }, { 1, -1 }, { -1, 1 }, { -1, -1 } }) do
		part(m, "Post", Vector3.new(0.4, h, 0.4), at * CFrame.new(c[1] * W / 2, h / 2, c[2] * L / 2), Enum.Material.Metal, FENCE)
	end
end
local function line(m, at, x, z, w, l)
	part(m, "Line", Vector3.new(w, 0.04, l), at * CFrame.new(x, 0.02, z), Enum.Material.SmoothPlastic, WHITE, { CanCollide = false })
end
for _, c in ipairs(COURTS) do
	local m = Instance.new("Model") m.Name = c.name
	local at = CFrame.new(c.x, TOP, c.z) * CFrame.Angles(0, math.rad(c.yaw), 0)
	local L, W = c.length, c.width
	if c.kind == "tennis" then
		part(m, "Surface", Vector3.new(W, 6.0, L), at * CFrame.new(0, -3.0, 0), Enum.Material.Ground, CLAY) -- deep: no gap on the slope
		local cw = W / c.n
		for k = 1, c.n do
			local x0 = -W / 2 + cw * (k - 0.5)
			local hl, hd, hs, sv = 23.77 * S / 2, 10.97 * S / 2, 8.23 * S / 2, 6.40 * S
			for _, s in ipairs({ -1, 1 }) do
				line(m, at, x0, s * hl, 2 * hd, LINE) -- baselines
				line(m, at, x0 + s * hd, 0, LINE, 2 * hl) -- doubles sidelines
				line(m, at, x0 + s * hs, 0, LINE, 2 * hl) -- singles sidelines
				line(m, at, x0, s * sv, 2 * hs, LINE) -- service lines
			end
			line(m, at, x0, 0, LINE, 2 * sv) -- centre service line
			part(m, "Net", Vector3.new(2 * hd + 1.8, 0.9 * S, 0.1), at * CFrame.new(x0, 0.9 * S / 2, 0), Enum.Material.Fabric, NET, { Transparency = 0.35 })
			for _, s in ipairs({ -1, 1 }) do
				part(m, "NetPost", Vector3.new(0.3, 1.07 * S, 0.3), at * CFrame.new(x0 + s * (hd + 0.9), 1.07 * S / 2, 0), Enum.Material.Metal, NET)
			end
			if k > 1 then line(m, at, -W / 2 + cw * (k - 1), 0, 0.6, L - 2) end -- the gap between two courts
		end
		fence(m, at, L, W, 3.5 * S)
	else
		part(m, "Surface", Vector3.new(W, 6.0, L), at * CFrame.new(0, -3.0, 0), Enum.Material.Grass, TURF)
		local pl, pw = L / 2 - 1.2 * S, W / 2 - 1.2 * S
		for _, s in ipairs({ -1, 1 }) do
			line(m, at, 0, s * pl, 2 * pw, LINE)
			line(m, at, s * pw, 0, LINE, 2 * pl)
			line(m, at, 0, s * (pl - 6 * S), 6 * S, LINE) -- the penalty box front, straight
			for _, t in ipairs({ -1, 1 }) do line(m, at, t * 3 * S, s * (pl - 3 * S), LINE, 6 * S) end
			local g = at * CFrame.new(0, 0, s * pl) -- goal: 3 x 2 m
			for _, t in ipairs({ -1, 1 }) do part(m, "GoalPost", Vector3.new(0.3, 2 * S, 0.3), g * CFrame.new(t * 1.5 * S, S, 0), Enum.Material.Metal, WHITE) end
			part(m, "GoalBar", Vector3.new(3 * S + 0.3, 0.3, 0.3), g * CFrame.new(0, 2 * S, 0), Enum.Material.Metal, WHITE)
			part(m, "GoalNet", Vector3.new(3 * S, 2 * S, 0.1), g * CFrame.new(0, S, s * 1.0 * S), Enum.Material.Fabric, WHITE, { Transparency = 0.6, CanCollide = false })
		end
		line(m, at, 0, 0, 2 * pw, LINE) -- half line
		local ring = part(m, "Circle", Vector3.new(0.04, 6 * S, 6 * S), at * CFrame.new(0, 0.02, 0) * CFrame.Angles(0, 0, math.rad(90)),
			Enum.Material.SmoothPlastic, WHITE, { Shape = Enum.PartType.Cylinder, CanCollide = false })
		part(m, "CircleIn", Vector3.new(0.05, 6 * S - 2 * LINE, 6 * S - 2 * LINE), ring.CFrame, Enum.Material.Grass, TURF,
			{ Shape = Enum.PartType.Cylinder, CanCollide = false })
		fence(m, at, L, W, 4 * S)
	end
	m.Parent = root
end
root.Parent = manual
return string.format("Manual/Courts made: %d courts, %d parts", #COURTS, count)
'''


def render(data: list[dict]) -> str:
    rows = ",\n".join("\t{ name = %s, kind = %s, x = %g, z = %g, yaw = %g, length = %g, width = %g, n = %d }"
                      % (json.dumps(d["name"]), json.dumps(d["kind"]), d["x"], d["z"], d["yaw"], d["length"], d["width"], d["n"]) for d in data)
    return LUAU.replace("--[[DATA]]", "{\n" + rows + "\n}")


if __name__ == "__main__":
    data = blocks()
    OUT.write_text(render(data), encoding="utf-8")
    # the satellite reads the green turf as crowns: build_luau.py keeps trees off these rectangles (covers: w across, d along)
    clear = [{"name": d["name"], "x": d["x"], "z": d["z"], "yaw": d["yaw"], "w": round(d["width"] + 4, 2), "d": round(d["length"] + 4, 2)} for d in data]
    path = common.cell_file(common.load_config(), CELL, "courts")
    path.write_text(json.dumps({"cell_id": CELL, "note": "Manual/Courts rectangles (studs); no satellite tree inside", "clear": clear},
                               ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(OUT, [(d["name"], round(d["length"] / 3.6, 1), round(d["width"] / 3.6, 1), d["n"]) for d in data])
